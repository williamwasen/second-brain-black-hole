// Builds the Obsidian plugin: obsidian/main.ts -> main.js, obsidian/styles.css -> styles.css (repo root).
//   node obsidian/esbuild.config.mjs             watch mode for development
//   node obsidian/esbuild.config.mjs production  one minified build for a release
import esbuild from 'esbuild';
import { builtinModules } from 'node:module';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const prod = process.argv[2] === 'production';
const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
Source: https://github.com/williamwasen/second-brain-black-hole (obsidian/ and src/)
*/
`;
const common = { bundle: true, logLevel: 'info', minify: prod, absWorkingDir: root };
const contexts = await Promise.all([
  esbuild.context({
    ...common,
    banner: { js: banner },
    entryPoints: ['obsidian/main.ts'],
    outfile: 'main.js',
    external: ['obsidian', 'electron', '@codemirror/*', '@lezer/*', ...builtinModules],
    format: 'cjs',
    target: 'es2021',
    sourcemap: prod ? false : 'inline',
    treeShaking: true,
  }),
  esbuild.context({ ...common, entryPoints: ['obsidian/styles.css'], outfile: 'styles.css' }),
]);
if (prod) {
  await Promise.all(contexts.map(context => context.rebuild()));
  process.exit(0);
}
await Promise.all(contexts.map(context => context.watch()));
